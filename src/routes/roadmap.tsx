import { createFileRoute, Link } from "@tanstack/react-router";
import { useServerFn } from "@tanstack/react-start";
import { useEffect, useMemo, useState } from "react";
import { motion } from "motion/react";
import { generateRoadmap, type Roadmap } from "@/lib/roadmap.functions";
import { useAccess } from "@/hooks/useAccess";
import { Icon } from "@/components/Primitives";
import { ProGate } from "@/components/ProGate";

export const Route = createFileRoute("/roadmap")({
  component: RoadmapPage,
  staticData: { sitemap: false },
  head: () => ({
    meta: [
      { title: "AI Study Roadmap — PG Prep" },
      {
        name: "description",
        content:
          "Type what you need to study and get a structured, phase-by-phase NEET PG roadmap you can tick off step by step.",
      },
      { property: "og:title", content: "AI Study Roadmap — PG Prep" },
      {
        property: "og:description",
        content: "A personalised, roadmap.sh-style study plan for NEET PG, generated by AI.",
      },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary" },
    ],
  }),
});

type ToolRoute = "/bank" | "/papers" | "/mock" | "/focus" | "/weak-spots";

const TOOLS: Array<{ match: RegExp; label: string; to: ToolRoute }> = [
  { match: /qbank/i, label: "QBank", to: "/bank" },
  { match: /pyq|vault|past[- ]year/i, label: "PYQ Vault", to: "/papers" },
  { match: /mock/i, label: "Mock Tests", to: "/mock" },
  { match: /focus/i, label: "Focus Lock", to: "/focus" },
  { match: /weak/i, label: "Weak Spots", to: "/weak-spots" },
];

function toolFor(resource: string) {
  return TOOLS.find((t) => t.match.test(resource));
}

function externalHref(resource: string) {
  return `https://www.google.com/search?q=${encodeURIComponent(`${resource} NEET PG`)}`;
}

function phaseTools(phase: Roadmap["phases"][number]) {
  const tools: ToolRoute[] = [];
  const externals: string[] = [];
  for (const s of phase.steps) {
    if (!s.resource) continue;
    const tool = toolFor(s.resource);
    if (tool) {
      if (!tools.includes(tool.to)) tools.push(tool.to);
    } else if (!externals.includes(s.resource)) {
      externals.push(s.resource);
    }
  }
  if (!tools.length) tools.push("/bank");
  return { tools, externals: externals.slice(0, 2) };
}

const SUGGESTIONS = [
  "Pharmacology for NEET PG in 6 weeks",
  "Full Medicine revision before INICET",
  "Pathology from scratch",
  "Final 30-day sprint before the exam",
];

type SavedMap = { goal: string; roadmap: Roadmap; done: string[] };

function storageKey(goal: string) {
  return `padida.roadmap.${goal.toLowerCase().replace(/[^a-z0-9]+/g, "-").slice(0, 60)}`;
}

function loadSaved(goal: string): SavedMap | null {
  try {
    const raw = localStorage.getItem(storageKey(goal));
    return raw ? (JSON.parse(raw) as SavedMap) : null;
  } catch {
    return null;
  }
}

function RoadmapPage() {
  const { isPro, loading } = useAccess();
  const generate = useServerFn(generateRoadmap);

  const [goal, setGoal] = useState("");
  const [weeks, setWeeks] = useState(8);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [current, setCurrent] = useState<SavedMap | null>(null);
  const [done, setDone] = useState<Set<string>>(new Set());

  useEffect(() => {
    if (!current) return;
    setDone(new Set(current.done));
  }, [current]);

  const totalSteps = useMemo(
    () => current?.roadmap.phases.reduce((n, p) => n + p.steps.length, 0) ?? 0,
    [current],
  );
  const pct = totalSteps ? Math.round((done.size / totalSteps) * 100) : 0;

  async function run(g: string) {
    const q = g.trim();
    if (!q || busy) return;
    setError("");

    const cached = loadSaved(q);
    if (cached) {
      setCurrent(cached);
      setGoal(q);
      return;
    }

    setBusy(true);
    try {
      const res = await generate({ data: { goal: q, weeks } });
      const saved: SavedMap = { goal: q, roadmap: res.roadmap, done: [] };
      try {
        localStorage.setItem(storageKey(q), JSON.stringify(saved));
      } catch {
        // storage full — roadmap still shows for this session
      }
      setCurrent(saved);
      setGoal(q);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Roadmap generation failed.");
    } finally {
      setBusy(false);
    }
  }

  function toggleStep(id: string) {
    if (!current) return;
    const next = new Set(done);
    if (next.has(id)) next.delete(id);
    else next.add(id);
    setDone(next);
    try {
      localStorage.setItem(
        storageKey(current.goal),
        JSON.stringify({ ...current, done: [...next] }),
      );
    } catch {
      // ignore
    }
  }

  if (loading) return null;

  if (!isPro) {
    return (
      <div className="mx-auto max-w-3xl px-4 py-10">
        <p className="label-eyebrow">Plan smarter</p>
        <h1 className="mt-1 font-display text-3xl font-bold tracking-tight md:text-4xl">
          AI Study <span className="text-primary">Roadmap</span>
        </h1>
        <p className="mt-2 max-w-xl text-sm text-muted-foreground">
          Type what you need to study and get a structured, phase-by-phase roadmap — like
          roadmap.sh, but for NEET PG.
        </p>
        <div className="mt-6">
          <ProGate feature="AI Study Roadmaps">{null}</ProGate>
        </div>
      </div>
    );
  }

  return (
    <div className="mx-auto max-w-3xl px-4 py-10">
      <p className="label-eyebrow">Plan smarter</p>
      <h1 className="mt-1 font-display text-3xl font-bold tracking-tight md:text-4xl">
        AI Study <span className="text-primary">Roadmap</span>
      </h1>
      <p className="mt-2 max-w-xl text-sm text-muted-foreground">
        Type what you need to study — a subject, a weak area, a countdown sprint — and get a
        structured, step-by-step roadmap you can tick off as you go.
      </p>

      <form
        onSubmit={(e) => {
          e.preventDefault();
          void run(goal);
        }}
        className="glass mt-6 flex flex-col gap-3 p-4 sm:flex-row sm:items-center"
      >
        <input
          value={goal}
          onChange={(e) => setGoal(e.target.value)}
          placeholder="e.g. Pharmacology for NEET PG"
          className="min-w-0 flex-1 rounded-full border border-border bg-surface-2 px-4 py-2.5 text-sm"
        />
        <select
          value={weeks}
          onChange={(e) => setWeeks(Number(e.target.value))}
          className="rounded-full border border-border bg-surface-2 px-3 py-2.5 text-sm"
          aria-label="Time available"
        >
          {[2, 4, 6, 8, 12, 16, 24].map((w) => (
            <option key={w} value={w}>
              {w} weeks
            </option>
          ))}
        </select>
        <button
          type="submit"
          disabled={busy || goal.trim().length < 3}
          className="btn-base btn-primary whitespace-nowrap px-5 py-2.5 text-sm disabled:opacity-50"
        >
          {busy ? "Drawing…" : "Build my roadmap"}
        </button>
      </form>

      {!current && !busy ? (
        <div className="mt-4 flex flex-wrap gap-2">
          {SUGGESTIONS.map((s) => (
            <button
              key={s}
              type="button"
              onClick={() => void run(s)}
              className="rounded-full border border-border bg-surface-2 px-3.5 py-1.5 text-xs font-semibold transition-colors hover:bg-tint"
            >
              {s}
            </button>
          ))}
        </div>
      ) : null}

      {busy ? (
        <div className="mt-10 flex items-center gap-3 text-sm text-muted-foreground">
          <span className="h-4 w-4 animate-spin rounded-full border-2 border-primary border-t-transparent" />
          Sketching your roadmap — this takes a few seconds…
        </div>
      ) : null}
      {error ? <p className="mt-4 text-sm font-semibold text-destructive">{error}</p> : null}

      {current ? (
        <section className="mt-10" aria-label="Generated roadmap">
          <div className="flex flex-wrap items-end justify-between gap-3">
            <div className="min-w-0">
              <h2 className="font-display text-xl font-bold tracking-tight">
                {current.roadmap.title}
              </h2>
              <p className="mt-1 text-sm text-muted-foreground">{current.roadmap.intro}</p>
            </div>
            <div className="shrink-0 text-right">
              <p className="font-display text-2xl font-bold text-primary">{pct}%</p>
              <p className="label-eyebrow">
                {done.size}/{totalSteps} steps
              </p>
            </div>
          </div>

          <div className="mt-3 h-1.5 overflow-hidden rounded-full bg-surface-2">
            <motion.div
              className="h-full rounded-full bg-primary"
              animate={{ width: `${pct}%` }}
              transition={{ duration: 0.5, ease: [0.22, 1, 0.36, 1] }}
            />
          </div>

          <ol className="relative mt-8 space-y-8 border-l-2 border-primary/25 pl-6">
            {current.roadmap.phases.map((phase, pi) => {
              const phaseDone = phase.steps.every((_, si) => done.has(`${pi}:${si}`));
              return (
                <motion.li
                  key={pi}
                  initial={{ opacity: 0, y: 16 }}
                  animate={{ opacity: 1, y: 0 }}
                  transition={{ duration: 0.4, delay: pi * 0.06, ease: [0.22, 1, 0.36, 1] }}
                  className="relative"
                >
                  <span
                    className={`absolute -left-[33px] flex h-5 w-5 items-center justify-center rounded-full border-2 ${
                      phaseDone
                        ? "border-primary bg-primary text-primary-foreground"
                        : "border-primary/50 bg-surface"
                    }`}
                  >
                    {phaseDone ? <Icon name="check" className="text-[12px]" /> : null}
                  </span>

                  <div className="glass p-4">
                    <p className="label-eyebrow">Phase {pi + 1}</p>
                    <h3 className="mt-0.5 font-display text-base font-bold">{phase.title}</h3>
                    <p className="mt-1 text-xs text-muted-foreground">{phase.summary}</p>

                    <ul className="mt-3 space-y-2">
                      {phase.steps.map((step, si) => {
                        const id = `${pi}:${si}`;
                        const isDone = done.has(id);
                        return (
                          <li key={si}>
                            <button
                              type="button"
                              onClick={() => toggleStep(id)}
                              className={`flex w-full items-start gap-3 rounded-xl border px-3 py-2.5 text-left transition-all duration-300 ${
                                isDone
                                  ? "border-primary/40 bg-tint"
                                  : "border-border bg-surface-2 hover:border-primary/40"
                              }`}
                            >
                              <span
                                className={`mt-0.5 flex h-4.5 w-4.5 shrink-0 items-center justify-center rounded-md border-2 ${
                                  isDone
                                    ? "border-primary bg-primary text-primary-foreground"
                                    : "border-muted-foreground/40"
                                }`}
                              >
                                {isDone ? <Icon name="check" className="text-[11px]" /> : null}
                              </span>
                              <span className="min-w-0 flex-1">
                                <span
                                  className={`block text-sm font-semibold ${isDone ? "line-through opacity-60" : ""}`}
                                >
                                  {step.title}
                                </span>
                                <span className="mt-0.5 block text-xs text-muted-foreground">
                                  {step.detail}
                                </span>
                                {step.resource ? (
                                  <span className="mt-1 inline-block rounded-full bg-tint px-2 py-0.5 text-[10px] font-bold text-primary">
                                    {step.resource}
                                  </span>
                                ) : null}
                              </span>
                            </button>
                          </li>
                        );
                      })}
                    </ul>
                    {(() => {
                      const { tools, externals } = phaseTools(phase);
                      return (
                        <div className="mt-3 flex flex-wrap items-center gap-2 border-t border-primary/10 pt-3">
                          <span className="text-[10px] font-bold uppercase tracking-wider text-muted-foreground">
                            Links
                          </span>
                          {tools.map((to) => {
                            const tool = TOOLS.find((t) => t.to === to)!;
                            return (
                              <Link
                                key={to}
                                to={to}
                                className="rounded-full bg-tint px-3 py-1 text-xs font-semibold text-primary transition-colors hover:bg-primary/20"
                              >
                                {tool.label} →
                              </Link>
                            );
                          })}
                          {externals.map((r) => (
                            <a
                              key={r}
                              href={externalHref(r)}
                              target="_blank"
                              rel="noopener noreferrer"
                              className="rounded-full bg-tint px-3 py-1 text-xs font-semibold text-primary transition-colors hover:bg-primary/20"
                            >
                              {r} ↗
                            </a>
                          ))}
                        </div>
                      );
                    })()}
                  </div>
                </motion.li>
              );
            })}
          </ol>

          <p className="mt-6 text-xs text-muted-foreground">
            Progress is saved on this device. Ready to practise?{" "}
            <Link to="/bank" className="font-semibold text-primary hover:underline">
              Open the QBank →
            </Link>
          </p>
        </section>
      ) : null}
    </div>
  );
}
