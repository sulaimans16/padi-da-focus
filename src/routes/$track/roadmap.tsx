function RoadmapPage() {
  const track = useTrack();
  const { isPro, loading } = useAccess();
  const { user } = useAuth();
  const generate = useServerFn(generateRoadmap);

  const [goal, setGoal] = useState("");
  const [weeks, setWeeks] = useState(8);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [current, setCurrent] = useState<SavedMap | null>(null);
  const [done, setDone] = useState<Set<string>>(new Set());

  useEffect(() => {
    try {
      const last = localStorage.getItem(LAST_KEY());
      if (!last) return;
      const saved = loadSaved(last);
      if (saved) {
        setCurrent(saved);
        setGoal(saved.goal);
      }
    } catch {
      // ignore
    }
  }, []);

  // Pull plans made on other devices (and push this device's) once signed in.
  useEffect(() => {
    if (!user) return;
    let live = true;
    void syncRoadmaps().then((m) => {
      if (!live || !m) return;
      setCurrent((cur) =>
        !cur ||
        cur.goal !== m.goal ||
        Date.parse(m.updatedAt ?? "") > Date.parse(cur.updatedAt ?? "")
          ? m
          : cur,
      );
      setGoal((g) => g || m.goal);
    });
    return () => {
      live = false;
    };
  }, [user]);

  useEffect(() => {
    if (!current) return;
    setDone(new Set(current.done));
  }, [current]);

  const openedGoal = current?.goal;
  useEffect(() => {
    if (current) markOpened(current);
    // Only when a different plan is opened, not on every progress change.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [openedGoal]);

  const totalSteps = useMemo(
    () => current?.roadmap.phases.reduce((n, p) => n + p.steps.length, 0) ?? 0,
    [current],
  );
  const pct = totalSteps ? Math.round((done.size / totalSteps) * 100) : 0;

  async function run(g: string) {
    const q = g.trim();
    if (!q || busy) return;
    setError("");

    const cached = loadSaved(q);
    if (cached) {
      setCurrent(cached);
      setGoal(q);
      return;
    }

    setBusy(true);
    try {
      const res = await generate({ data: { goal: q, weeks, exam: track.id } });
      setCurrent(saveRoadmap({ goal: q, roadmap: res.roadmap, done: [] }));
      setGoal(q);
    } catch (e) {
      setError(e instanceof Error ? e.message : "Roadmap generation failed.");
    } finally {
      setBusy(false);
    }
  }

  function toggleStep(id: string) {
    if (!current) return;
    const next = new Set(done);
    if (next.has(id)) next.delete(id);
    else next.add(id);
    setDone(next);
    saveRoadmap({ ...current, done: [...next] }, { debounce: 800 });
  }

  if (loading) return null;

  if (!isPro) {
    return (
      <div className="mx-auto max-w-3xl px-4 py-10">
        <p className="label-eyebrow">Plan smarter</p>
        <h1 className="mt-1 font-display text-3xl font-bold tracking-tight md:text-4xl">
          AI Study <span className="text-primary">Roadmap</span>
        </h1>
        <MascotSays mood="happy" size={80} className="mt-4">
          Tell me your goal and I'll draw you a route, phase by phase. Then we walk it together.
        </MascotSays>
        <div className="mt-6">
          <ProGate feature="AI Study Roadmaps">{null}</ProGate>
        </div>
        <div
          className="pointer-events-none mt-8 select-none opacity-60 [mask-image:linear-gradient(to_bottom,black_55%,transparent)]"
          aria-hidden
        >
          <RoadmapTrail
            roadmap={SAMPLE}
            done={new Set(["0:0", "0:1", "1:0"])}
            interactive={false}
          />
        </div>
      </div>
    );
  }

  return (
    <div className="mx-auto max-w-3xl px-4 py-10">
      <p className="label-eyebrow">Plan smarter</p>
      <h1 className="mt-1 font-display text-3xl font-bold tracking-tight md:text-4xl">
        AI Study <span className="text-primary">Roadmap</span>
      </h1>
      <MascotSays mood={busy ? "think" : current ? "happy" : "idle"} size={80} className="mt-4">
        {busy
          ? "Hmm, let me plot the best route for you…"
          : current
            ? pct === 100
              ? "We made it! Pick a new goal whenever you're ready."
              : `${totalSteps - done.size} steps to go. I'll walk with you.`
            : "What do you want to conquer? A subject, a weak area, a final sprint. I'll map the route."}
      </MascotSays>

      <form
        onSubmit={(e) => {
          e.preventDefault();
          void run(goal);
        }}
        className="card-pop mt-6 flex flex-col gap-3 p-4 sm:flex-row sm:items-center"
      >
        <input
          value={goal}
          onChange={(e) => setGoal(e.target.value)}
          placeholder={
            track.id === "neet_ug"
              ? "e.g. Organic chemistry for NEET UG"
              : "e.g. Pharmacology for NEET PG"
          }
          className="min-w-0 flex-1 rounded-full border-2 border-glass-line bg-surface-2 px-4 py-3 text-sm outline-none transition-colors focus:border-primary"
        />
        <select
          value={weeks}
          onChange={(e) => setWeeks(Number(e.target.value))}
          className="rounded-full border-2 border-glass-line bg-surface-2 px-3 py-3 text-sm"
          aria-label="Time available"
        >
          {[2, 4, 6, 8, 12, 16, 24].map((w) => (
            <option key={w} value={w}>
              {w} weeks
            </option>
          ))}
        </select>
        <button
          type="submit"
          disabled={busy || goal.trim().length < 3}
          className="btn-base btn-primary h-12 whitespace-nowrap px-6 text-sm"
        >
          <Icon name={busy ? "hourglass_top" : "route"} filled className="text-[18px]" />
          {busy ? "Drawing…" : "Draw my route"}
        </button>
      </form>

      {!current && !busy ? (
        <div className="mt-4 flex flex-wrap gap-2">
          {(SUGGESTIONS[track.id] ?? []).map((s) => (
            <button
              key={s}
              type="button"
              onClick={() => void run(s)}
              className="btn-base btn-ghost px-3.5 py-1.5 text-xs"
            >
              {s}
            </button>
          ))}
        </div>
      ) : null}

      {busy ? (
        <div className="mt-10 flex flex-col items-center gap-2 text-sm text-muted-foreground">
          <svg viewBox="0 0 200 120" className="h-32 w-56" aria-hidden>
            <path
              d="M20 110 C 20 70, 100 80, 100 60 C 100 40, 180 50, 180 10"
              fill="none"
              stroke="var(--color-primary)"
              strokeWidth={5}
              strokeLinecap="round"
              strokeDasharray="4 12"
              className="roadmap-draw"
            />
          </svg>
          <Mascot mood="walk" size={72} />
          Sketching your route. This takes a few seconds…
        </div>
      ) : null}
      {error ? <p className="mt-4 text-sm font-semibold text-destructive">{error}</p> : null}

      {current ? (
        <section className="mt-10" aria-label="Your study route">
          <div className="flex flex-wrap items-end justify-between gap-3">
            <div className="min-w-0">
              <h2 className="font-display text-xl font-bold tracking-tight">
                {current.roadmap.title}
              </h2>
              <p className="mt-1 text-sm text-muted-foreground">{current.roadmap.intro}</p>
            </div>
            <div className="shrink-0 text-right">
              <p className="font-display text-2xl font-bold text-primary">{pct}%</p>
              <p className="label-eyebrow">
                {done.size}/{totalSteps} steps
              </p>
            </div>
          </div>

          <ProgressBar value={pct / 100} color="var(--color-xp)" className="mt-3 h-4" />
          <p className="mt-2 flex items-center gap-1 text-xs text-muted-foreground">
            <Icon name={user ? "cloud_done" : "smartphone"} className="text-[16px]" />
            {user
              ? "Synced to your account, so it follows you to any device."
              : "Saved on this device. Sign in to keep it on every device."}
          </p>

          <div className="mt-10">
            <RoadmapTrail
              roadmap={current.roadmap}
              done={done}
              onToggle={toggleStep}
              phaseLinks={(p) => phaseLinkNodes(p, track.slug, track.name)}
            />
          </div>
        </section>
      ) : null}
    </div>
  );
}
