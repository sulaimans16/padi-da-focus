type ToolRoute =
  "/$track/bank" | "/$track/papers" | "/$track/mock" | "/$track/focus" | "/$track/weak-spots";

const TOOLS: Array<{ match: RegExp; label: string; to: ToolRoute }> = [
  { match: /qbank/i, label: "QBank", to: "/$track/bank" },
  { match: /pyq|vault|past[- ]year/i, label: "PYQ Vault", to: "/$track/papers" },
  { match: /mock/i, label: "Mock Tests", to: "/$track/mock" },
  { match: /focus/i, label: "Focus Lock", to: "/$track/focus" },
  { match: /weak/i, label: "Weak Spots", to: "/$track/weak-spots" },
];

function toolFor(resource: string) {
  return TOOLS.find((t) => t.match.test(resource));
}

function externalHref(resource: string, exam: string) {
  return `https://www.google.com/search?q=${encodeURIComponent(`${resource} ${exam}`)}`;
}

function phaseTools(phase: Roadmap["phases"][number]) {
  const tools: ToolRoute[] = [];
  const externals: string[] = [];
  for (const s of phase.steps) {
    if (!s.resource) continue;
    const tool = toolFor(s.resource);
    if (tool) {
      if (!tools.includes(tool.to)) tools.push(tool.to);
    } else if (!externals.includes(s.resource)) {
      externals.push(s.resource);
    }
  }
  if (!tools.length) tools.push("/$track/bank");
  return { tools, externals: externals.slice(0, 2) };
}

function phaseLinkNodes(
  phase: Roadmap["phases"][number],
  trackSlug: string,
  examName: string,
): TrailLink[] {
  const { tools, externals } = phaseTools(phase);
  const cls = "btn-base btn-ghost px-3 py-1 text-xs text-primary";
  return [
    ...tools.map((to) => ({
      key: to,
      label: TOOLS.find((t) => t.to === to)!.label,
      node: (
        <Link to={to} params={{ track: trackSlug }} className={cls}>
          {TOOLS.find((t) => t.to === to)!.label} →
        </Link>
      ),
    })),
    ...externals.map((r) => ({
      key: r,
      label: r,
      node: (
        <a
          href={externalHref(r, examName)}
          target="_blank"
          rel="noopener noreferrer"
          className={cls}
        >
          {r} ↗
        </a>
      ),
    })),
  ];
}

